-- Play tab, step 2 of 2: arcade scores and leaderboards (Tile Drop).
-- Safe to run again. Run after 01_wordle_duel.sql.
--
-- Scores can only be added through submit_arcade_score(), which turns
-- away impossible scores. Leaderboards show your servers or everyone.

create table if not exists public.arcade_scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  game text not null check (game in ('tile_drop')),
  play_date date not null,
  score integer not null check (score between 0 and 10000000),
  lines integer not null default 0 check (lines between 0 and 100000),
  created_at timestamptz not null default now()
);

create index if not exists arcade_scores_board_index on public.arcade_scores (game, play_date, score desc);
create index if not exists arcade_scores_user_index on public.arcade_scores (user_id, game);

alter table public.arcade_scores enable row level security;
revoke all on public.arcade_scores from anon, authenticated;


-- p_play_date is the player's date (kept within a day of the server's,
-- for time zones). A score can't be more than the most a game with that
-- many cleared lines could give.
create or replace function public.submit_arcade_score(
  p_game text,
  p_play_date date,
  p_score integer,
  p_lines integer
)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := (select auth.uid());
  level_cap integer;
begin
  if me is null then
    raise exception 'Log in first';
  end if;

  if p_game not in ('tile_drop') then
    raise exception 'Unknown game.';
  end if;

  if p_play_date is null or p_play_date not between current_date - 1 and current_date + 1 then
    raise exception 'Scores can only be saved for today.';
  end if;

  if p_lines is null or p_lines < 0 or p_score is null or p_score < 0 then
    raise exception 'That score is not valid.';
  end if;

  -- Clearing 4 lines at once scores 800 x level, the level goes up every
  -- 10 lines, and dropping pieces adds a little. Allow comfortably more.
  level_cap := p_lines / 10 + 1;

  if p_score > 5000 + p_lines * (250 * level_cap + 200) then
    raise exception 'That score is not possible.';
  end if;

  insert into public.arcade_scores (user_id, game, play_date, score, lines)
  values (me, p_game, p_play_date, p_score, p_lines);

  return json_build_object(
    'best_today', (
      select max(score) from public.arcade_scores
      where user_id = me and game = p_game and play_date = p_play_date
    )
  );
end;
$$;


-- Best score per player for today, this week (Monday on) or all time;
-- for one of your servers or for everyone. Top 50, plus your own row.
create or replace function public.arcade_leaderboard(
  p_game text,
  p_period text,
  p_server uuid,
  p_today date
)
returns json
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  me uuid := (select auth.uid());
  from_date date;
  result json;
begin
  if me is null then
    raise exception 'Log in first';
  end if;

  if p_server is not null and not public.is_server_member(p_server) then
    raise exception 'You are not in that server.';
  end if;

  from_date := case p_period
    when 'today' then p_today
    when 'week' then date_trunc('week', p_today)::date
    else '-infinity'::date
  end;

  with best as (
    select s.user_id, max(s.score) as score
    from public.arcade_scores s
    where s.game = p_game
      and s.play_date between from_date and p_today
      and (p_server is null or s.user_id in (
        select m.user_id from public.server_members m where m.server_id = p_server
      ))
    group by s.user_id
  ),
  ranked as (
    select b.user_id, b.score, p.username,
           rank() over (order by b.score desc) as rank
    from best b
    left join public.profiles p on p.user_id = b.user_id
  )
  select json_build_object(
    'rows', coalesce((
      select json_agg(json_build_object(
        'rank', r.rank, 'user_id', r.user_id, 'username', r.username,
        'score', r.score, 'is_me', r.user_id = me
      ) order by r.rank, r.username)
      from (select * from ranked order by rank, username limit 50) r
    ), '[]'::json),
    'me', (
      select json_build_object('rank', r.rank, 'score', r.score)
      from ranked r where r.user_id = me
    )
  )
  into result;

  return result;
end;
$$;

revoke all on function public.submit_arcade_score(text, date, integer, integer) from public, anon;
revoke all on function public.arcade_leaderboard(text, text, uuid, date) from public, anon;
grant execute on function public.submit_arcade_score(text, date, integer, integer) to authenticated;
grant execute on function public.arcade_leaderboard(text, text, uuid, date) to authenticated;

-- Check: should say true twice.
select 'submit_arcade_score function' as item, (to_regprocedure('public.submit_arcade_score(text, date, integer, integer)') is not null)::text as value
union all
select 'arcade_leaderboard function', (to_regprocedure('public.arcade_leaderboard(text, text, uuid, date)') is not null)::text;
