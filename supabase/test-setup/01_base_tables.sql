-- Recreates the original Daily Game Hub tables and their security rules
-- (copied from the real database's structure) in an empty Supabase
-- project, so the test app works the same way. Safe to run again.

create table if not exists public.profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  username text not null,
  display_name text,
  created_at timestamptz not null default now(),
  constraint profiles_username_unique unique (username),
  constraint profiles_username_format check (username ~ '^[a-z0-9_]{3,24}$')
);

create table if not exists public.games (
  game_key text primary key,
  name text not null,
  url text not null,
  category text not null,
  description text not null default '',
  icon text not null default '🎮',
  color text not null default '#7c3aed',
  is_official boolean not null default false,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists games_created_by_index on public.games (created_by);

create table if not exists public.user_games (
  user_id uuid not null references auth.users (id) on delete cascade,
  game_key text not null references public.games (game_key) on delete cascade,
  is_visible boolean not null default true,
  is_favorite boolean not null default false,
  sort_order integer not null default 0,
  added_at timestamptz not null default now(),
  primary key (user_id, game_key)
);

create index if not exists user_games_user_sort_index on public.user_games (user_id, sort_order);

create table if not exists public.daily_scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (user_id) on delete cascade,
  game_id text not null,
  play_date date not null default current_date,
  completed boolean not null default true,
  result_text text,
  numeric_score numeric,
  score_unit text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint one_score_per_day unique (user_id, game_id, play_date)
);

create index if not exists daily_scores_user_date_index on public.daily_scores (user_id, play_date desc);
create index if not exists daily_scores_game_date_index on public.daily_scores (game_id, play_date desc);

create table if not exists public.daily_game_status (
  user_id uuid not null references auth.users (id) on delete cascade,
  game_key text not null,
  play_date date not null,
  completed boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (user_id, game_key, play_date)
);

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users (id) on delete cascade,
  addressee_id uuid not null references auth.users (id) on delete cascade,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  constraint friendships_unique_direction unique (requester_id, addressee_id)
);

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  type text not null,
  game text,
  message text not null,
  name text,
  email text,
  status text not null default 'new'
);

create table if not exists public.game_preferences (
  user_id uuid primary key references auth.users (id) on delete cascade,
  game_order jsonb not null default '[]',
  favorite_games jsonb not null default '[]'
);

