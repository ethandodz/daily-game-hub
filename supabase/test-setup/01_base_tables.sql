-- Policies, same as the real database
drop policy if exists "Create own profile" on public.profiles;
create policy "Create own profile" on public.profiles for insert to authenticated
  with check ((select auth.uid()) = user_id);
drop policy if exists "Update own profile" on public.profiles;
create policy "Update own profile" on public.profiles for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "View profiles" on public.profiles;
create policy "View profiles" on public.profiles for select to authenticated using (true);

drop policy if exists "Authenticated users can view games" on public.games;
create policy "Authenticated users can view games" on public.games for select to authenticated using (true);
drop policy if exists "Users can create custom games" on public.games;
create policy "Users can create custom games" on public.games for insert to authenticated
  with check (is_official = false and created_by = (select auth.uid()));
drop policy if exists "Users can update their custom games" on public.games;
create policy "Users can update their custom games" on public.games for update to authenticated
  using (is_official = false and created_by = (select auth.uid()))
  with check (is_official = false and created_by = (select auth.uid()));
drop policy if exists "Users can delete their custom games" on public.games;
create policy "Users can delete their custom games" on public.games for delete to authenticated
  using (is_official = false and created_by = (select auth.uid()));

