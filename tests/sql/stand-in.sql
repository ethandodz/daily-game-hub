do $$ begin if not exists (select 1 from pg_roles where rolname='anon') then create role anon nologin; end if; end $$;
do $$ begin if not exists (select 1 from pg_roles where rolname='authenticated') then create role authenticated nologin; end if; end $$;
create schema auth;
create table auth.users (id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
grant usage on schema auth to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;
grant usage on schema public to anon, authenticated;
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;

-- Existing tables (columns from the production snapshot)
create table public.games (game_key text primary key, name text not null, url text not null, category text not null,
  description text not null default '', icon text not null default '🎮', color text not null default '#7c3aed',
  is_official boolean not null default false, created_by uuid, created_at timestamptz not null default now());
create table public.profiles (user_id uuid primary key, username text not null unique, display_name text, created_at timestamptz not null default now());
create table public.friendships (id bigint generated by default as identity primary key, requester_id uuid not null, addressee_id uuid not null,
  status text not null default 'pending', created_at timestamptz not null default now(), unique (requester_id, addressee_id));
create table public.daily_scores (id bigint generated by default as identity primary key, user_id uuid not null, game_id text not null,
  play_date date not null default current_date, completed boolean not null default true, result_text text, numeric_score numeric,
  score_unit text, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  constraint one_score_per_day unique (user_id, game_id, play_date));

alter table public.games enable row level security;
alter table public.profiles enable row level security;
alter table public.friendships enable row level security;
alter table public.daily_scores enable row level security;

-- Existing policies (copied from the production snapshot)
create policy "View profiles" on public.profiles for select to authenticated using (true);
create policy "Authenticated users can view games" on public.games for select to authenticated using (true);
create policy "View own friendships" on public.friendships for select to authenticated
  using (((select auth.uid()) = requester_id) or ((select auth.uid()) = addressee_id));
create policy "Add own scores" on public.daily_scores for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Update own scores" on public.daily_scores for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Delete own scores" on public.daily_scores for delete to authenticated using ((select auth.uid()) = user_id);
create policy "View own scores" on public.daily_scores for select to authenticated using ((select auth.uid()) = user_id);
create policy "Friends view scores" on public.daily_scores for select to authenticated using (exists (select 1 from friendships
  where friendships.status = 'accepted' and ((friendships.requester_id = (select auth.uid()) and friendships.addressee_id = daily_scores.user_id)
  or (friendships.addressee_id = (select auth.uid()) and friendships.requester_id = daily_scores.user_id))));

