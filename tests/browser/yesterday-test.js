const m = require('../helpers/mock.js');
const assert = (c, msg) => { console.log((c ? 'PASS ' : 'FAIL ') + msg); if (!c) process.exitCode = 1; };
const ME = '11111111-1111-1111-1111-111111111111', ETHAN = '22222222-2222-2222-2222-222222222222', MAYA = '33333333-3333-3333-3333-333333333333';
const y = m.day(1);
m.serverState.servers.push({ id: 'srv-y1', name: 'Ball Knowers', owner_id: ME, invite_code: 'YYY111', start_date: m.day(5), created_at: m.day(5) });
m.serverState.servers.push({ id: 'srv-y2', name: 'Work Crew', owner_id: ETHAN, invite_code: 'YYY222', start_date: m.day(5), created_at: m.day(6) });
for (const [sid, users] of [['srv-y1', [ME, MAYA]], ['srv-y2', [ME, ETHAN]]]) users.forEach(u => m.serverState.members.push({ server_id: sid, user_id: u, role: 'member', joined_at: m.day(5) }));
['wordle', 'krillion'].forEach((g, i) => m.serverState.games.push({ server_id: 'srv-y1', game_key: g, sort_order: i }));
m.serverState.games.push({ server_id: 'srv-y2', game_key: 'connections', sort_order: 0 });
m.tables.daily_scores.length = 0;
const add = (u, g, n, completed = true) => m.tables.daily_scores.push({ id: m.tables.daily_scores.length + 1, user_id: u, game_id: g, play_date: y, numeric_score: n, completed, result_text: null });
add(ME, 'wordle', 3); add(MAYA, 'wordle', 4); add(ME, 'krillion', 400); add(MAYA, 'krillion', 300);
add(ME, 'connections', 2); add(ETHAN, 'connections', 0);
m.server.listen(0, async () => {
  const browser = await m.chromium.launch();
  const { page, errors } = await m.setup(browser, { ...m.devices['iPhone 13'], colorScheme: 'dark' });
  await page.goto(`http://localhost:${m.server.address().port}/`); await page.waitForTimeout(2500);
  const lines = await page.$$eval('#yesterdayLines .yesterday-line', l => l.map(x => x.textContent));
  assert(await page.isVisible('#yesterdayBanner') && lines.length === 2, 'banner shows a line per server');
  assert(lines[0] === '👑 Yesterday in Ball Knowers: you won 2 games', 'won: ' + lines[0]);
  assert(lines[1] === 'Yesterday in Work Crew: you won none · @ethan 1', 'didn’t win: ' + lines[1]);
  await page.screenshot({ path: process.argv[3] + '-banner.png', clip: { x: 0, y: 0, width: 390, height: 320 } });
  await page.click('#yesterdayLines .yesterday-line:nth-child(2)'); await page.waitForTimeout(1500);
  assert(await page.isVisible('#socialView') && await page.$eval('#serverSwitcher .filter-button.active', c => c.textContent) === 'Work Crew' && await page.$eval('[data-board-day="yesterday"]', b => b.classList.contains('active')), 'tapping opens that server on Yesterday');
  assert((await page.textContent('#serverBoardSummary')).includes('(final)'), 'board shows yesterday final');
  await page.click('[data-tab-button="games"]');
  await page.click('#yesterdayCloseButton'); await page.waitForTimeout(200);
  await page.reload(); await page.waitForTimeout(2500);
  assert(!(await page.isVisible('#yesterdayBanner')), '✕ hides it until tomorrow (stays hidden after reload)');
  assert(errors.length === 0, 'no console errors ' + errors.join('|'));
  await browser.close(); m.server.close();
});
